/**
 * Minimal, dependency-free CSV parser. Handles quoted fields, embedded commas,
 * and quoted quotes. Returns a two-dimensional array of strings.
 */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;

  // Normalize mixed line endings.
  const src = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');

  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inQuotes) {
      if (c === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += c;
    }
  }
  // Final field (file may not end with newline).
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

/** Drop empty trailing rows and trim fields. */
export function cleanCsv(text: string): string[][] {
  const parsed = parseCsv(text);
  const trimmed = parsed.map((r) => r.map((c) => c.trim()));
  return trimmed.filter((r) => r.some((c) => c.length > 0));
}